use crate::ast::*;
use crate::semantic::layout;
use std::fmt::Write;

pub fn generate(module: &Module) -> String {
    let mut out = String::new();

    writeln!(out, "// AUTO-GENERATED by xso-idlc 0.1.0. DO NOT EDIT.").unwrap();
    writeln!(out, "// Module: {} v{}", module.name, module.version).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#![allow(non_camel_case_types, dead_code)]").unwrap();
    writeln!(out, "extern crate alloc;").unwrap();
    writeln!(out, "use alloc::vec::Vec;").unwrap();
    writeln!(out, "use alloc::string::String;").unwrap();
    writeln!(out, "use crate::lib::{{string_view, Result}};").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub mod {}_bridge {{", module.name).unwrap();
    writeln!(out, "    use super::*;").unwrap();
    writeln!(out).unwrap();

    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut out, e),
            Item::Error(e) => gen_error(&mut out, e),
            Item::Struct(s) => gen_struct(&mut out, module, s),
            Item::Interface(i) => gen_interface(&mut out, module, i),
            Item::TypeAlias(t) => gen_type_alias(&mut out, t),
        }
        writeln!(out).unwrap();
    }

    writeln!(out, "}}").unwrap();
    out
}

fn rust_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => match p.as_str() {
            "u8" => "u8".into(), "u16" => "u16".into(),
            "u32" => "u32".into(), "u64" => "u64".into(),
            "i8" => "i8".into(), "i16" => "i16".into(),
            "i32" => "i32".into(), "i64" => "i64".into(),
            "bool" => "bool".into(), "unit" => "()".into(),
            _ => p.clone(),
        },
        TypeRef::BorrowedStr => "string_view".into(),
        TypeRef::OwnedString => "String".into(),
        TypeRef::Named(n) => n.clone(),
        TypeRef::Vec(t) => format!("Vec<{}>", rust_type(t)),
        TypeRef::Option(t) => format!("Option<{}>", rust_type(t)),
        TypeRef::Result(ok, err) =>
            format!("Result<{}, {}>", rust_type(ok), rust_type(err)),
    }
}

fn gen_enum(out: &mut String, e: &EnumDef) {
    let repr = rust_type(&TypeRef::Primitive(e.underlying.clone()));
    writeln!(out, "    #[repr({})]", repr).unwrap();
    writeln!(out, "    #[derive(Clone, Copy, PartialEq, Eq)]").unwrap();
    writeln!(out, "    pub enum {} {{", e.name).unwrap();
    for v in &e.variants {
        writeln!(out, "        {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "    }}").unwrap();
    let size = match e.underlying.as_str() {
        "u8" | "i8" => 1, "u16" | "i16" => 2,
        "u32" | "i32" => 4, _ => 8,
    };
    writeln!(out, "    const _: () = assert!(core::mem::size_of::<{}>() == {});",
             e.name, size).unwrap();
}

fn gen_error(out: &mut String, e: &ErrorDef) {
    let repr = rust_type(&TypeRef::Primitive(e.underlying.clone()));
    writeln!(out, "    #[repr({})]", repr).unwrap();
    writeln!(out, "    #[derive(Clone, Copy, PartialEq, Eq)]").unwrap();
    writeln!(out, "    pub enum {} {{", e.name).unwrap();
    for v in &e.variants {
        writeln!(out, "        {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "    }}").unwrap();
}

fn gen_struct(out: &mut String, module: &Module, s: &StructDef) {
    writeln!(out, "    #[repr(C, packed)]").unwrap();
    writeln!(out, "    pub struct {} {{", s.name).unwrap();
    for f in &s.fields {
        writeln!(out, "        pub {}: {},", f.name, rust_type(&f.ty)).unwrap();
    }
    writeln!(out, "    }}").unwrap();

    let layout = layout::compute_struct_layout(module, s);
    writeln!(out, "    const _: () = assert!(core::mem::size_of::<{}>() == {});",
             s.name, layout.size).unwrap();

    let mut offset = 0usize;
    for f in &s.fields {
        let fl = layout::layout_of(module, &f.ty);
        offset = (offset + fl.align - 1) & !(fl.align - 1);
        writeln!(out, "    const _: () = assert!(core::mem::offset_of!({}, {}) == {});",
                 s.name, f.name, offset).unwrap();
        offset += fl.size;
    }
}

fn gen_type_alias(out: &mut String, t: &TypeAliasDef) {
    writeln!(out, "    pub type {} = {};", t.name, rust_type(&t.target)).unwrap();
}

fn gen_interface(out: &mut String, _module: &Module, i: &InterfaceDef) {
    // trait
    writeln!(out, "    pub trait {} {{", i.name).unwrap();
    for m in &i.methods {
        let params = m.params.iter()
            .map(|p| format!("{}: {}", p.name, rust_type(&p.ty)))
            .collect::<Vec<_>>().join(", ");
        let self_arg = if params.is_empty() {
            "&self".to_string()
        } else {
            format!("&self, {}", params)
        };
        writeln!(out, "        fn {}({}) -> {};",
                 m.name, self_arg, rust_type(&m.ret)).unwrap();
    }
    writeln!(out, "    }}").unwrap();

    // vtable 结构
    writeln!(out, "    #[repr(C)]").unwrap();
    writeln!(out, "    pub struct {}VTable {{", i.name).unwrap();
    for m in &i.methods {
        let params = m.params.iter()
            .map(|p| rust_type(&p.ty))
            .collect::<Vec<_>>().join(", ");
        let self_ = if params.is_empty() {
            "*mut core::ffi::c_void".to_string()
        } else {
            format!("*mut core::ffi::c_void, {}", params)
        };
        writeln!(out,
                 "        pub {}: unsafe extern \"C\" fn({}) -> {},",
                 m.name, self_, rust_type(&m.ret)).unwrap();
    }
    writeln!(out, "    }}").unwrap();
}