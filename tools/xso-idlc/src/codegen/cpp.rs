use crate::ast::*;
use crate::semantic::layout;
use std::fmt::Write;

pub fn generate(module: &Module) -> String {
    let mut out = String::new();
    let guard = format!("XSO_GEN_{}_H", module.name.to_uppercase());
    let ns = format!("xso::{}::bridge", module.name);

    writeln!(out, "// AUTO-GENERATED by xso-idlc 0.1.0. DO NOT EDIT.").unwrap();
    writeln!(out, "// Module: {} v{}", module.name, module.version).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out, "#include <stdint.h>").unwrap();
    writeln!(out, "#include <stddef.h>").unwrap();
    writeln!(out, "// NOTE: assumes xso::Result<T,E>, xso::string_view,").unwrap();
    writeln!(out, "//       xso::Vector<T>, xso::Optional<T> from kernel/lib/*").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "namespace {} {{", ns).unwrap();
    writeln!(out).unwrap();

    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut out, e),
            Item::Error(e) => gen_error(&mut out, e),
            Item::Struct(s) => gen_struct(&mut out, module, s),
            Item::Interface(i) => gen_interface(&mut out, module, i),
            Item::TypeAlias(t) => gen_type_alias(&mut out, t),
        }
        writeln!(out).unwrap();
    }

    writeln!(out, "}} // namespace {}", ns).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#endif // {}", guard).unwrap();
    out
}

fn cpp_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => match p.as_str() {
            "u8" => "uint8_t".into(),
            "u16" => "uint16_t".into(),
            "u32" => "uint32_t".into(),
            "u64" => "uint64_t".into(),
            "i8" => "int8_t".into(),
            "i16" => "int16_t".into(),
            "i32" => "int32_t".into(),
            "i64" => "int64_t".into(),
            "bool" => "bool".into(),
            "unit" => "void".into(),
            _ => p.clone(),
        },
        TypeRef::BorrowedStr => "xso::string_view".into(),
        TypeRef::OwnedString => "xso::String".into(),
        TypeRef::Named(n) => n.clone(),
        TypeRef::Vec(t) => format!("xso::Vector<{}>", cpp_type(t)),
        TypeRef::Option(t) => format!("xso::Optional<{}>", cpp_type(t)),
        TypeRef::Result(ok, err) =>
            format!("xso::Result<{}, {}>", cpp_type(ok), cpp_type(err)),
    }
}

fn gen_enum(out: &mut String, e: &EnumDef) {
    let underlying = cpp_type(&TypeRef::Primitive(e.underlying.clone()));
    writeln!(out, "enum class {} : {} {{", e.name, underlying).unwrap();
    for v in &e.variants {
        writeln!(out, "    {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "}};").unwrap();
}

fn gen_error(out: &mut String, e: &ErrorDef) {
    let underlying = cpp_type(&TypeRef::Primitive(e.underlying.clone()));
    writeln!(out, "enum class {} : {} {{", e.name, underlying).unwrap();
    for v in &e.variants {
        writeln!(out, "    {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "}};").unwrap();
}

fn gen_struct(out: &mut String, module: &Module, s: &StructDef) {
    writeln!(out, "struct {} {{", s.name).unwrap();
    for f in &s.fields {
        writeln!(out, "    {} {};", cpp_type(&f.ty), f.name).unwrap();
    }
    writeln!(out, "}} __attribute__((packed));").unwrap();

    let layout = layout::compute_struct_layout(module, s);
    writeln!(out, "static_assert(sizeof({}) == {}, \"layout drift\");",
             s.name, layout.size).unwrap();

    let mut offset = 0usize;
    for f in &s.fields {
        let fl = layout::layout_of(module, &f.ty);
        offset = (offset + fl.align - 1) & !(fl.align - 1);
        writeln!(out, "static_assert(offsetof({}, {}) == {}, \"field offset\");",
                 s.name, f.name, offset).unwrap();
        offset += fl.size;
    }
}

fn gen_type_alias(out: &mut String, t: &TypeAliasDef) {
    writeln!(out, "using {} = {};", t.name, cpp_type(&t.target)).unwrap();
}

fn gen_interface(out: &mut String, _module: &Module, i: &InterfaceDef) {
    writeln!(out, "class {} {{", i.name).unwrap();
    writeln!(out, "public:").unwrap();

    // vtable 结构
    writeln!(out, "    struct VTable {{").unwrap();
    for m in &i.methods {
        let params = m.params.iter()
            .map(|p| format!("{}, {}", cpp_type(&p.ty), p.name))
            .collect::<Vec<_>>().join(", ");
        let ret = cpp_type(&m.ret);
        let params2 = if m.params.is_empty() {
            "void* self".to_string()
        } else {
            format!("void* self, {}", params)
        };
        writeln!(out, "        {} (*{})({});", ret, m.name, params2).unwrap();
    }
    writeln!(out, "    }};").unwrap();
    writeln!(out).unwrap();

    // 转发方法
    for m in &i.methods {
        let params = m.params.iter()
            .map(|p| format!("{}, {}", cpp_type(&p.ty), p.name))
            .collect::<Vec<_>>().join(", ");
        let ret = cpp_type(&m.ret);
        let args = m.params.iter()
            .map(|p| p.name.clone())
            .collect::<Vec<_>>().join(", ");
        let args = if args.is_empty() {
            format!("self_, {}", args) // 留空
        } else {
            format!("self_, {}", args)
        };
        writeln!(out, "    {} {}({}) {{", ret, m.name, params).unwrap();
        writeln!(out, "        return vt_->{}({});", m.name, args.trim_end_matches(", ")).unwrap();
        writeln!(out, "    }}").unwrap();
    }

    writeln!(out).unwrap();
    writeln!(out, "    void* self_ = nullptr;").unwrap();
    writeln!(out, "    VTable* vt_ = nullptr;").unwrap();
    writeln!(out, "}};").unwrap();
}