//! 文档后端（Markdown）：通过 `Emitter` 的 Markdown 构造器产出，
//! 本文件不出现写死的 Markdown 表格/标题文本。

use crate::ast::*;
use crate::bridge_ir::BridgeIr;
use crate::codegen::emitter::Emitter;

pub fn generate(ir: &BridgeIr) -> String {
    let module = &ir.module;
    let mut em = Emitter::new();

    em.md_heading(1, &format!("ABI Reference: {} v{}", module.name, module.version));
    em.blank();
    em.md_quote("AUTO-GENERATED by xso-idlc. DO NOT EDIT.");
    em.blank();

    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut em, e),
            Item::Error(e) => gen_error(&mut em, e),
            Item::Struct(s) => gen_struct(&mut em, ir, s),
            Item::Interface(i) => gen_interface(&mut em, i),
            Item::TypeAlias(t) => {
                em.md_heading(2, &format!("Type `{}`", t.name));
                em.blank();
                em.line(&format!("Alias for `{}`", ty_debug(&t.target)));
                em.blank();
            }
        }
    }
    em.finish()
}

fn ty_debug(ty: &TypeRef) -> String { format!("{:?}", ty) }

fn gen_enum(em: &mut Emitter, e: &EnumDef) {
    em.md_heading(2, &format!("Enum `{}`", e.name));
    em.blank();
    em.line(&format!("Underlying: `{}`", e.underlying));
    em.blank();
    em.md_table_row(&["Name".to_string(), "Value".to_string()]);
    em.md_table_sep(2);
    for v in &e.variants {
        em.md_table_row(&[v.name.clone(), v.value.to_string()]);
    }
    em.blank();
}

fn gen_error(em: &mut Emitter, e: &ErrorDef) {
    em.md_heading(2, &format!("Error `{}`", e.name));
    em.blank();
    em.line(&format!("Underlying: `{}`", e.underlying));
    em.blank();
    em.md_table_row(&["Name".to_string(), "Value".to_string()]);
    em.md_table_sep(2);
    for v in &e.variants {
        em.md_table_row(&[v.name.clone(), v.value.to_string()]);
    }
    em.blank();
}

fn gen_struct(em: &mut Emitter, ir: &BridgeIr, s: &StructDef) {
    let suffix = if s.opaque { " (opaque)" } else { "" };
    em.md_heading(2, &format!("Struct `{}`{}", s.name, suffix));
    em.blank();

    if let Some(layout) = ir.layout_of(&s.name) {
        em.line(&format!("Size: `{}`  Align: `{}`", layout.size, layout.align));
        em.blank();
    }

    if s.opaque {
        em.line("Fields hidden by design; pass by `@owned` / `@borrowed` only.");
        em.blank();
        return;
    }

    em.md_table_row(&["Field".to_string(), "Type".to_string(), "Offset".to_string()]);
    em.md_table_sep(3);
    if let Some(offsets) = ir.field_offsets(&s.name) {
        for (fname, _, off) in offsets {
            let ty = s.fields.iter().find(|f| &f.name == fname).map(|f| ty_debug(&f.ty));
            em.md_table_row(&[fname.clone(), ty.unwrap_or_default(), off.to_string()]);
        }
    } else {
        for f in &s.fields {
            em.md_table_row(&[f.name.clone(), ty_debug(&f.ty), "-".to_string()]);
        }
    }
    em.blank();
}

fn gen_interface(em: &mut Emitter, i: &InterfaceDef) {
    let suffix = if i.opaque { " (opaque)" } else { "" };
    em.md_heading(2, &format!("Interface `{}`{}", i.name, suffix));
    em.blank();
    em.md_table_row(&["Method".to_string(), "Self".to_string(), "Signature".to_string()]);
    em.md_table_sep(3);
    for m in &i.methods {
        let self_kind = match m.self_ownership {
            Some(Ownership::Owned) => "@owned",
            Some(Ownership::Borrowed) => "@borrowed",
            Some(Ownership::Value) => "by value",
            None => "-",
        };
        let params = m.params.iter()
            .map(|p| {
                let own = match p.ownership {
                    Ownership::Owned => "@owned ",
                    Ownership::Borrowed => "@borrowed ",
                    Ownership::Value => "",
                };
                format!("{}{}: {}", own, p.name, ty_debug(&p.ty))
            })
            .collect::<Vec<_>>().join(", ");
        em.md_table_row(&[m.name.clone(), self_kind.to_string(),
            format!("({}) -> {}", params, ty_debug(&m.ret))]);
    }
    em.blank();
}
