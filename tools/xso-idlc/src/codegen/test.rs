use crate::ast::Module;
use std::fmt::Write;

/// 第一步只生成骨架，第二步扩展为 fuzz 与 layout 对拍
pub fn generate(module: &Module) -> String {
    let mut out = String::new();
    writeln!(out, "// AUTO-GENERATED by xso-idlc. TODO: expand in step 2.").unwrap();
    writeln!(out, "// Module: {} v{}", module.name, module.version).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#[test]").unwrap();
    writeln!(out, "fn smoke_test() {{").unwrap();
    writeln!(out, "    // TODO: generated fuzz cases").unwrap();
    writeln!(out, "}}").unwrap();
    out
}