//! C++ 后端：全部通过 `Emitter` 的语义方法 + `syntax` 构造器产出源码，
//! 本文件不出现任何写死的源码字符串（关键字/标点/模板一律来自 `syntax`）。

use crate::ast::*;
use crate::bridge_ir::BridgeIr;
use crate::codegen::emitter::Emitter;
use crate::codegen::naming;
use crate::codegen::syntax;

pub fn generate(ir: &BridgeIr) -> String {
    let module = &ir.module;
    let mut em = Emitter::new();
    let ns = naming::cxx_namespace(&module.name);

    // ===== 文件头 =====
    em.cpp_comment("AUTO-GENERATED by xso-idlc. DO NOT EDIT.");
    em.cpp_comment(&format!("Module: {} v{}", module.name, module.version));
    em.cpp_pragma_once();
    em.cpp_include("stdint.h", false);
    em.cpp_include("stddef.h", false);
    em.cpp_include("stdlib.h", false);
    em.cpp_include("type_traits", false);
    em.cpp_include(naming::ANCHOR_HEADER, true);
    em.cpp_comment("假定内核提供 xso::Result<T,E>, xso::string_view, xso::Vector<T> 等");
    em.blank();

    em.cpp_ns_open(&ns);
    em.blank();

    // ===== 边界完整性违规 -> fail-closed =====
    em.cpp_comment("边界完整性违规（如非法判别式）-> fail-closed，绝不进入未定义行为");
    em.open(&syntax::cpp::fn_noreturn(
        "inline void", naming::BOUNDARY_VIOLATION, ""));
    em.stmt(&syntax::cpp::expr_stmt("abort()"));
    em.cpp_fn_close();
    em.blank();

    // ===== ABI 指纹（与 anchor / Rust 端一致）=====
    let module_up = module.name.to_uppercase();
    em.cpp_comment("ABI 指纹：布局描述符的 FNV-1a 校验和（应与 anchor 头一致）");
    em.cpp_constexpr("uint32_t", &naming::checksum_const(&module_up),
                     &format!("0x{:08x}u", ir.fingerprint()));
    em.cpp_constexpr("uint32_t", naming::ALGO_VERSION,
                     &format!("{}u", crate::bridge_ir::FINGERPRINT_ALGO_VERSION));
    em.cpp_constexpr("uint32_t", naming::IR_VERSION, &format!("{}u", ir.ir_version));
    em.blank();

    // ===== 中间布局：规范桥接载体 =====
    let needs_vec = module.items.iter().any(|it| match it {
        Item::Struct(s) => s.fields.iter().any(|f| uses_bridge_vec(&f.ty)),
        Item::Interface(i) => i.methods.iter().any(|m| {
            m.params.iter().any(|p| uses_bridge_vec(&p.ty))
            || matches!(&m.ret, TypeRef::Result(ok, _) if !is_unit(ok) && uses_bridge_vec(ok))
        }),
        _ => false,
    });
    let needs_pair = module.items.iter().any(|it| match it {
        Item::Struct(s) => s.fields.iter().any(|f| matches!(f.ty, TypeRef::Map(_, _))),
        Item::Interface(i) => i.methods.iter().any(|m| {
            m.params.iter().any(|p| matches!(p.ty, TypeRef::Map(_, _)))
            || matches!(&m.ret, TypeRef::Result(ok, _) if matches!(ok.as_ref(), TypeRef::Map(_, _)))
        }),
        _ => false,
    });

    if needs_pair {
        em.cpp_comment("中间布局：关联容器的键值对载体");
        em.cpp_template("typename K, typename V");
        em.stmt(&syntax::cpp::struct_one_line(
            naming::PAIR, &format!("{} {};", syntax::cpp::member("K", "key"),
                                   syntax::cpp::member("V", "val"))));
        em.blank();
    }
    if needs_vec {
        // 参照 cxx：必须保持平凡拷贝构造 + 平凡析构，否则 SysV ABI 改为按内存传参
        em.cpp_comment("中间布局：序列/切片/字符串/集合的统一载体 (ptr, len)，与 Rust 端逐字节一致");
        em.cpp_comment("它是**借用视图**（不拥有缓冲）；所有权转移请使用带 drop 壳的类型。");
        em.cpp_template("typename T");
        em.cpp_struct_open(naming::VEC);
        em.cpp_member("const T*", "ptr");
        em.cpp_member("size_t", "len");
        em.cpp_comment("Important in order for System V ABI to pass in registers.");
        em.stmt(&syntax::cpp::copy_ctor_default(naming::VEC));
        em.stmt(&syntax::cpp::dtor_default(naming::VEC));
        let cq = syntax::cpp::NOEXCEPT;
        em.stmt(&syntax::cpp::method_one_line("size_t", "size", "", &format!("const {}", cq), "return len"));
        em.stmt(&syntax::cpp::method_one_line("bool", "empty", "", &format!("const {}", cq), "return len == 0"));
        em.stmt(&syntax::cpp::method_one_line("const T*", "data", "", &format!("const {}", cq), "return ptr"));
        em.cpp_struct_close();
        // 布局与平凡性锁定
        let carrier = format!("{}<uint8_t>", naming::VEC);
        em.cpp_static_assert(
            &format!("{} == {}", syntax::cpp::sizeof_expr(&carrier), naming::CARRIER_SIZE),
            "carrier size drift");
        em.cpp_static_assert(
            &format!("{} == {}", syntax::cpp::alignof_expr(&carrier), naming::CARRIER_ALIGN),
            "carrier align drift");
        em.cpp_static_assert(
            &em.cpp_trivially_copyable(&carrier),
            "carrier must stay trivially copyable to be passed in registers");
        em.blank();
    }

    // ===== 不透明类型前向声明 =====
    for item in &module.items {
        match item {
            Item::Struct(s) if s.opaque => {
                em.stmt(&syntax::cpp::forward_decl(syntax::cpp::CLASS, &s.name));
                em.stmt(&syntax::cpp::using_alias(
                    &format!("{}Ptr", s.name), &format!("{}*", s.name)));
            }
            Item::Interface(i) => {
                em.stmt(&syntax::cpp::forward_decl(syntax::cpp::CLASS, &i.name));
                em.stmt(&syntax::cpp::using_alias(
                    &format!("{}Ptr", i.name), &format!("{}*", i.name)));
            }
            _ => {}
        }
    }
    em.blank();

    // ===== 条目 =====
    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut em, e),
            Item::Error(e) => gen_error(&mut em, e),
            Item::Struct(s) if !s.opaque => gen_struct(&mut em, ir, s),
            Item::Struct(_) => {} // 已前向声明
            Item::Interface(i) => gen_interface(&mut em, i),
            Item::TypeAlias(t) => gen_type_alias(&mut em, t),
        }
        em.blank();
    }

    em.cpp_ns_close();
    em.finish()
}

// ===================== 类型映射 =====================

/// 易用侧（公共包装方法）的 C++ 类型
fn cpp_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => cpp_prim(p),
        TypeRef::BorrowedStr => naming::CXX_STRING_VIEW.into(),
        TypeRef::OwnedString => naming::CXX_STRING.into(),
        TypeRef::Named(n) => n.clone(),
        TypeRef::App { name, args } =>
            cpp_type(&TypeRef::Named(crate::semantic::mono::mangle(name, args))),
        TypeRef::Vec(t) => format!("{}<{}>", naming::CXX_VECTOR, cpp_type(t)),
        TypeRef::Set(t) => format!("{}<{}>", naming::CXX_VECTOR, cpp_type(t)),
        TypeRef::Map(k, v) => format!("{}<{}<{}, {}>>",
            naming::CXX_VECTOR, naming::PAIR, cpp_type(k), cpp_type(v)),
        TypeRef::Option(t) => format!("{}<{}>", naming::CXX_OPTIONAL, cpp_type(t)),
        TypeRef::Owned(t) => format!("{}<{}>", naming::CXX_UNIQUE_PTR, cpp_type(t)),
        TypeRef::Borrowed(t) => format!("const {}&", cpp_type(t)),
        TypeRef::Result(ok, err) =>
            format!("{}<{}, {}>", naming::CXX_RESULT, cpp_type(ok), cpp_type(err)),
    }
}

fn is_unit(ty: &TypeRef) -> bool {
    matches!(ty, TypeRef::Primitive(p) if p == "unit")
}

fn cpp_prim(p: &str) -> String {
    match p {
        "u8" => "uint8_t", "u16" => "uint16_t", "u32" => "uint32_t", "u64" => "uint64_t",
        "i8" => "int8_t", "i16" => "int16_t", "i32" => "int32_t", "i64" => "int64_t",
        "bool" => "bool", "unit" => "void",
        _ => p,
    }.to_string()
}

/// 容器元素类型（指针所指类型）
fn cpp_elem(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => cpp_prim(p),
        TypeRef::Named(n) => n.clone(),
        _ => "void".to_string(),
    }
}

/// FFI 边界类型：与 Rust 端 ffi_ty 严格对应（收敛为中间布局规范载体）
fn cpp_ffi_ty(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => cpp_prim(p),
        TypeRef::Named(n) => n.clone(),
        TypeRef::App { name, args } =>
            cpp_ffi_ty(&TypeRef::Named(crate::semantic::mono::mangle(name, args))),
        TypeRef::BorrowedStr | TypeRef::OwnedString =>
            naming::carrier(naming::VEC, "uint8_t"),
        TypeRef::Vec(t) => naming::carrier(naming::VEC, &cpp_ffi_ty(t)),
        TypeRef::Set(t) => naming::carrier(naming::VEC, &cpp_ffi_ty(t)),
        TypeRef::Map(k, v) => naming::carrier(naming::VEC,
            &naming::carrier(naming::PAIR, &format!("{}, {}", cpp_ffi_ty(k), cpp_ffi_ty(v)))),
        TypeRef::Owned(t) => format!("{}*", cpp_elem(t)),
        TypeRef::Borrowed(t) => format!("const {}*", cpp_elem(t)),
        TypeRef::Option(t) => format!("const {}*", cpp_elem(t)),
        TypeRef::Result(_, _) => "void*".to_string(),
    }
}

fn uses_bridge_vec(ty: &TypeRef) -> bool {
    matches!(ty,
        TypeRef::Vec(_) | TypeRef::Set(_) | TypeRef::Map(_, _)
        | TypeRef::BorrowedStr | TypeRef::OwnedString)
}

// ===================== 条目生成 =====================

/// 判别式安全转换：`<Enum>_from_code`（非法返回 false，调用方 fail-closed）
fn gen_codec(em: &mut Emitter, name: &str, variants: &[Variant]) {
    em.open(&syntax::cpp::fn_inline(
        "bool", &naming::from_code_fn(name),
        &format!("int32_t code, {}& out", name)));
    em.open(&syntax::cpp::switch_open("code"));
    for v in variants {
        let cast = syntax::cpp::static_cast("int32_t", &v.value.to_string());
        em.stmt(&syntax::cpp::case(
            &cast,
            &format!("out = {}::{}; return true", name, v.name)));
    }
    em.stmt(&syntax::cpp::default("return false"));
    em.close("}");
    em.cpp_fn_close();
}

fn gen_enum(em: &mut Emitter, e: &EnumDef) {
    let und = cpp_prim(&e.underlying);
    em.cpp_enum_open(&e.name, &und);
    for v in &e.variants { em.cpp_enumerator(&v.name, v.value); }
    em.cpp_enum_close();
    em.cpp_static_assert(
        &format!("{} == {}", syntax::cpp::sizeof_expr(&e.name),
                 naming::layout_size_macro(&e.name)),
        "layout drift");
    gen_codec(em, &e.name, &e.variants);
}

fn gen_error(em: &mut Emitter, e: &ErrorDef) {
    let und = cpp_prim(&e.underlying);
    em.cpp_enum_open(&e.name, &und);
    for v in &e.variants { em.cpp_enumerator(&v.name, v.value); }
    em.cpp_enum_close();
    em.cpp_static_assert(
        &format!("{} == {}", syntax::cpp::sizeof_expr(&e.name),
                 naming::layout_size_macro(&e.name)),
        "layout drift");
    gen_codec(em, &e.name, &e.variants);
}

fn gen_struct(em: &mut Emitter, ir: &BridgeIr, s: &StructDef) {
    em.cpp_comment("字段使用「中间布局」规范载体，保证与 anchor 断言、Rust 端逐字节一致。");
    em.cpp_struct_open(&s.name);
    for f in &s.fields { em.cpp_member(&cpp_ffi_ty(&f.ty), &f.name); }
    em.cpp_struct_close();
    // 参照 cxx 的可重定位检查
    em.cpp_static_assert(
        &em.cpp_trivially_copyable(&s.name),
        "shared struct must be trivially copyable to cross the boundary");
    em.cpp_static_assert(
        &format!("{} == {}", syntax::cpp::sizeof_expr(&s.name),
                 naming::layout_size_macro(&s.name)),
        "layout drift");
    em.cpp_static_assert(
        &format!("{} == {}", syntax::cpp::alignof_expr(&s.name),
                 naming::layout_align_macro(&s.name)),
        "align drift");
    if let Some(fields) = ir.field_offsets(&s.name) {
        for (fname, _, off) in fields {
            em.cpp_static_assert(
                &format!("{} == {}", syntax::cpp::offsetof_expr(&s.name, fname), off),
                "offset drift");
        }
    }
}

fn gen_type_alias(em: &mut Emitter, t: &TypeAliasDef) {
    em.stmt(&syntax::cpp::using_alias(&t.name, &cpp_type(&t.target)));
}

fn gen_interface(em: &mut Emitter, i: &InterfaceDef) {
    em.cpp_class_open(&i.name);
    em.cpp_access(syntax::cpp::PUBLIC);

    // ===== VTable：FFI 边界，稳定 ABI =====
    em.cpp_comment("VTable：FFI 边界使用稳定 ABI（规范载体 + i32 状态 + out 指针）");
    em.cpp_struct_open("VTable");
    for m in &i.methods {
        let self_ty = match m.self_ownership {
            Some(Ownership::Owned) => "void*",
            Some(Ownership::Borrowed) | Some(Ownership::Value) | None => "const void*",
        };
        let mut params = vec![format!("{} self", self_ty)];
        for p in &m.params {
            params.push(format!("{} {}", cpp_ffi_ty(&p.ty), p.name));
        }
        let (ret_ty, out_param) = match &m.ret {
            TypeRef::Result(ok, _err) => {
                if is_unit(ok) {
                    ("int32_t".to_string(), None)
                } else {
                    ("int32_t".to_string(), Some(format!("{}* out", cpp_ffi_ty(ok))))
                }
            }
            TypeRef::Primitive(p) if p == "unit" => ("void".to_string(), None),
            other => (cpp_ffi_ty(other), None),
        };
        if let Some(op) = out_param { params.push(op); }
        em.stmt(&syntax::cpp::fn_ptr_field(&ret_ty, &m.name, &params.join(", ")));
    }
    em.cpp_struct_close();
    em.blank();

    // ===== 公共包装方法 =====
    em.cpp_comment("公共包装方法：易用签名，内部负责与 FFI 边界类型互转");
    for m in &i.methods {
        let mut pub_params: Vec<String> = Vec::new();
        for p in &m.params {
            pub_params.push(format!("{} {}", cpp_type(&p.ty), p.name));
        }
        let ret_cpp = cpp_type(&m.ret);
        em.open(&syntax::cpp::method_open(&ret_cpp, &m.name, &pub_params.join(", ")));

        // 收敛为 XsoVec 的边界参数：由公共容器 .data()/.size() 统一拼装
        let mut call_args: Vec<String> = vec!["self_".to_string()];
        for p in &m.params {
            let fft = cpp_ffi_ty(&p.ty);
            if fft.starts_with(naming::VEC) {
                let vname = format!("{}_v", p.name);
                em.stmt(&syntax::cpp::var_init(
                    &fft, &vname,
                    &format!("{{ {}.data(), {}.size() }}", p.name, p.name)));
                call_args.push(vname);
            } else {
                call_args.push(p.name.clone());
            }
        }

        match &m.ret {
            TypeRef::Result(ok, err) => {
                let err_ty = cpp_type(err);
                if is_unit(ok) {
                    em.stmt(&syntax::cpp::var_init(
                        "int32_t", "e",
                        &format!("vt_->{}({})", m.name, call_args.join(", "))));
                    em.stmt(&syntax::cpp::if_stmt("e == 0", &syntax::cpp::return_stmt(
                        &syntax::cpp::result_call(naming::CXX_RESULT, "void", "ok", ""))));
                    em.stmt(&syntax::cpp::var_brace_init(&err_ty, "err"));
                    em.stmt(&syntax::cpp::if_stmt(
                        &format!("!{}(e, err)", naming::from_code_fn(&err_ty)),
                        &syntax::cpp::expr_stmt(&format!("{}()", naming::BOUNDARY_VIOLATION))));
                    em.stmt(&syntax::cpp::return_stmt(
                        &syntax::cpp::result_call(naming::CXX_RESULT, "void", "err", "err")));
                } else {
                    let out_ty = cpp_ffi_ty(ok);
                    em.stmt(&syntax::cpp::var_brace_init(&out_ty, "out"));
                    call_args.push("&out".to_string());
                    em.stmt(&syntax::cpp::var_init(
                        "int32_t", "e",
                        &format!("vt_->{}({})", m.name, call_args.join(", "))));
                    em.stmt(&syntax::cpp::if_stmt("e == 0", &syntax::cpp::return_stmt(
                        &syntax::cpp::result_call(
                            naming::CXX_RESULT, &format!("{}, {}", out_ty, err_ty), "ok", "out"))));
                    em.stmt(&syntax::cpp::var_brace_init(&err_ty, "err"));
                    em.stmt(&syntax::cpp::if_stmt(
                        &format!("!{}(e, err)", naming::from_code_fn(&err_ty)),
                        &syntax::cpp::expr_stmt(&format!("{}()", naming::BOUNDARY_VIOLATION))));
                    em.stmt(&syntax::cpp::return_stmt(
                        &syntax::cpp::result_call(
                            naming::CXX_RESULT, &format!("{}, {}", out_ty, err_ty), "err", "err")));
                }
            }
            _ => {
                em.stmt(&syntax::cpp::return_stmt(
                    &format!("vt_->{}({})", m.name, call_args.join(", "))));
            }
        }
        em.cpp_fn_close();
    }

    em.blank();
    em.stmt(&syntax::cpp::member("void*", "self_ = nullptr"));
    em.stmt(&syntax::cpp::member("VTable*", "vt_ = nullptr"));
    em.cpp_class_close();
}
