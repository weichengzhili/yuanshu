use crate::ast::*;
use std::fmt::Write;

pub fn generate(module: &Module) -> String {
    let mut out = String::new();

    writeln!(out, "# ABI Reference: {} v{}", module.name, module.version).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "> AUTO-GENERATED by xso-idlc. DO NOT EDIT.").unwrap();
    writeln!(out).unwrap();

    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut out, e),
            Item::Error(e) => gen_error(&mut out, e),
            Item::Struct(s) => gen_struct(&mut out, s),
            Item::Interface(i) => gen_interface(&mut out, i),
            Item::TypeAlias(t) => {
                writeln!(out, "## Type `{}`", t.name).unwrap();
                writeln!(out).unwrap();
                writeln!(out, "Alias for `{:?}`", t.target).unwrap();
                writeln!(out).unwrap();
            }
        }
    }

    out
}

fn gen_enum(out: &mut String, e: &EnumDef) {
    writeln!(out, "## Enum `{}`", e.name).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "Underlying: `{}`", e.underlying).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "| Name | Value |").unwrap();
    writeln!(out, "|---|---|").unwrap();
    for v in &e.variants {
        writeln!(out, "| {} | {} |", v.name, v.value).unwrap();
    }
    writeln!(out).unwrap();
}

fn gen_error(out: &mut String, e: &ErrorDef) {
    writeln!(out, "## Error `{}`", e.name).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "Underlying: `{}`", e.underlying).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "| Name | Value |").unwrap();
    writeln!(out, "|---|---|").unwrap();
    for v in &e.variants {
        writeln!(out, "| {} | {} |", v.name, v.value).unwrap();
    }
    writeln!(out).unwrap();
}

fn gen_struct(out: &mut String, s: &StructDef) {
    writeln!(out, "## Struct `{}`", s.name).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "| Field | Type |").unwrap();
    writeln!(out, "|---|---|").unwrap();
    for f in &s.fields {
        writeln!(out, "| {} | `{:?}` |", f.name, f.ty).unwrap();
    }
    writeln!(out).unwrap();
}

fn gen_interface(out: &mut String, i: &InterfaceDef) {
    writeln!(out, "## Interface `{}`", i.name).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "| Method | Signature |").unwrap();
    writeln!(out, "|---|---|").unwrap();
    for m in &i.methods {
        let params = m.params.iter()
            .map(|p| format!("{}: {:?}", p.name, p.ty))
            .collect::<Vec<_>>().join(", ");
        writeln!(out, "| {} | ({}) -> {:?} |", m.name, params, m.ret).unwrap();
    }
    writeln!(out).unwrap();
}