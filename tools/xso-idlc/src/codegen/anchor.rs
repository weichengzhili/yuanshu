//! 布局锚点：C++ 和 Rust 两端断言同一个常量，
//! 杜绝两端平行计算导致的布局漂移。
//!
//! 同样通过 `Emitter` 产出，不在本文件写死源码文本。

    let _ = syntax::cpp::DEFINE; // 宏名由 anchor_define 统一给出
use crate::bridge_ir::BridgeIr;
use crate::codegen::emitter::Emitter;
use crate::codegen::naming;
use crate::codegen::syntax;

/// C 风格块注释
fn c_comment(em: &mut Emitter, text: &str) {
    em.comment_raw(&format!("/* {} */", text));
}

pub fn generate(ir: &BridgeIr) -> String {
    let mut em = Emitter::new();
    let module_up = ir.module.name.to_uppercase();

    c_comment(&mut em, "AUTO-GENERATED by xso-idlc. DO NOT EDIT.");
    c_comment(&mut em, "布局唯一真相：C++ 与 Rust 两侧断言此文件的常量");
    // 审计信息（确定性：不含时间戳，保证生成幂等）
    c_comment(&mut em, &format!(
        "audit: module={} version={} ir_version={} algo={} fingerprint=0x{:08x}",
        ir.module.name, ir.module.version, ir.ir_version,
        crate::bridge_ir::FINGERPRINT_ALGO_VERSION, ir.fingerprint()));
    em.cpp_pragma_once();
    em.blank();

    // 指纹算法版本：算法变更时整体可控失效（而不是静默漂移）
    c_comment(&mut em, "ABI 指纹算法版本：算法升级时递增，使旧的校验和整体失效");
    em.anchor_define(naming::ALGO_VERSION,
                     &crate::bridge_ir::FINGERPRINT_ALGO_VERSION.to_string());
    // ABI 指纹（跨语言校验和：两端可运行期比对）
    c_comment(&mut em, "ABI 指纹：布局描述符的 FNV-1a 校验和，两端应完全一致");
    em.anchor_define(&naming::checksum_const(&module_up),
                     &format!("0x{:08x}u", ir.fingerprint()));
    em.anchor_define(&naming::ir_version_const(&module_up), &ir.ir_version.to_string());
    em.blank();

    // 共享结构体布局
    for (name, layout) in &ir.type_layouts {
        em.anchor_define(&naming::layout_size_macro(name), &layout.size.to_string());
        em.anchor_define(&naming::layout_align_macro(name), &layout.align.to_string());
        if let Some(fields) = ir.field_offsets(name) {
            for (fname, _, off) in fields {
                em.anchor_define(&naming::layout_offset_macro(name, fname), &off.to_string());
            }
        }
        em.blank();
    }

    // 枚举 / 错误
    for (name, layout) in &ir.enum_sizes {
        em.anchor_define(&naming::layout_size_macro(name), &layout.size.to_string());
        em.anchor_define(&naming::layout_align_macro(name), &layout.align.to_string());
        em.blank();
    }

    em.finish()
}
