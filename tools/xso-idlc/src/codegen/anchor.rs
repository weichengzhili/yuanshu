//! 布局锚点：C++ 和 Rust 两端断言同一个常量，
//! 杜绝两端平行计算导致的布局漂移。

use crate::bridge_ir::BridgeIr;
use std::fmt::Write;

pub fn generate(ir: &BridgeIr) -> String {
    let mut out = String::new();

    writeln!(out, "/* AUTO-GENERATED by xso-idlc 0.1.0. DO NOT EDIT. */").unwrap();
    writeln!(out, "/* 布局唯一真相：C++ 与 Rust 两侧断言此文件的常量 */").unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out).unwrap();

    // 共享结构体
    for (name, layout) in &ir.type_layouts {
        writeln!(out, "#define XSO_LAYOUT_{}_SIZE  {}", name, layout.size).unwrap();
        writeln!(out, "#define XSO_LAYOUT_{}_ALIGN {}", name, layout.align).unwrap();
        if let Some(fields) = ir.field_offsets(name) {
            for (fname, _, off) in fields {
                writeln!(out, "#define XSO_LAYOUT_{}_OFF_{} {}",
                         name, fname, off).unwrap();
            }
        }
        writeln!(out).unwrap();
    }

    // 枚举
    for (name, layout) in &ir.enum_sizes {
        writeln!(out, "#define XSO_LAYOUT_{}_SIZE  {}", name, layout.size).unwrap();
        writeln!(out, "#define XSO_LAYOUT_{}_ALIGN {}", name, layout.align).unwrap();
        writeln!(out).unwrap();
    }

    out
}