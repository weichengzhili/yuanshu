use crate::ast::*;
use crate::bridge_ir::BridgeIr;
use std::fmt::Write;

pub fn generate(ir: &BridgeIr) -> String {
    let module = &ir.module;
    let mut out = String::new();
    let ns = format!("xso::{}::bridge", module.name);

    writeln!(out, "// AUTO-GENERATED by xso-idlc 0.1.0. DO NOT EDIT.").unwrap();
    writeln!(out, "// Module: {} v{}", module.name, module.version).unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out, "#include <stdint.h>").unwrap();
    writeln!(out, "#include <stddef.h>").unwrap();
    writeln!(out, "#include \"layout_anchor.h\"").unwrap();
    writeln!(out, "// 假定内核提供 xso::Result<T,E>, xso::string_view, xso::Vector<T> 等").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "namespace {} {{", ns).unwrap();
    writeln!(out).unwrap();

    // FFI 边界载体：与 Rust 端 XsoVec<T> 逐字节一致（ptr, len）
    writeln!(out, "// FFI 边界载体：切片/字符串以 (指针, 长度) 传递，布局稳定").unwrap();
    writeln!(out, "template <typename T>").unwrap();
    writeln!(out, "struct XsoVec {{ const T* ptr; size_t len; }};").unwrap();
    writeln!(out).unwrap();

    // 先声明不透明类型（前向声明）
    for item in &module.items {
        match item {
            Item::Struct(s) if s.opaque => {
                writeln!(out, "class {};  // opaque", s.name).unwrap();
                writeln!(out, "using {}Ptr = {}*;", s.name, s.name).unwrap();
            }
            Item::Interface(i) => {
                writeln!(out, "class {};  // opaque interface", i.name).unwrap();
                writeln!(out, "using {}Ptr = {}*;", i.name, i.name).unwrap();
            }
            _ => {}
        }
    }
    writeln!(out).unwrap();

    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut out, e),
            Item::Error(e) => gen_error(&mut out, e),
            Item::Struct(s) if !s.opaque => gen_struct(&mut out, ir, s),
            Item::Struct(_) => {} // 已声明
            Item::Interface(i) => gen_interface(&mut out, i),
            Item::TypeAlias(t) => gen_type_alias(&mut out, t),
        }
        writeln!(out).unwrap();
    }

    writeln!(out, "}} // namespace {}", ns).unwrap();
    out
}

fn cpp_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => match p.as_str() {
            "u8" => "uint8_t".into(), "u16" => "uint16_t".into(),
            "u32" => "uint32_t".into(), "u64" => "uint64_t".into(),
            "i8" => "int8_t".into(), "i16" => "int16_t".into(),
            "i32" => "int32_t".into(), "i64" => "int64_t".into(),
            "bool" => "bool".into(), "unit" => "void".into(),
            _ => p.clone(),
        },
        TypeRef::BorrowedStr => "xso::string_view".into(),
        TypeRef::OwnedString => "xso::String".into(),
        TypeRef::Named(n) => n.clone(),
        TypeRef::Vec(t) => format!("xso::Vector<{}>", cpp_type(t)),
        TypeRef::Option(t) => format!("xso::Optional<{}>", cpp_type(t)),
        TypeRef::Owned(t) => format!("xso::UniquePtr<{}>", cpp_type(t)),
        TypeRef::Borrowed(t) => format!("const {}&", cpp_type(t)),
        TypeRef::Result(ok, err) =>
            format!("xso::Result<{}, {}>", cpp_type(ok), cpp_type(err)),
    }
}

fn is_unit(ty: &TypeRef) -> bool {
    matches!(ty, TypeRef::Primitive(p) if p == "unit")
}

fn cpp_prim(p: &str) -> String {
    match p {
        "u8" => "uint8_t", "u16" => "uint16_t", "u32" => "uint32_t", "u64" => "uint64_t",
        "i8" => "int8_t", "i16" => "int16_t", "i32" => "int32_t", "i64" => "int64_t",
        "bool" => "bool", "unit" => "void",
        _ => p,
    }.to_string()
}

/// 容器元素类型（指针所指类型）
fn cpp_elem(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => cpp_prim(p),
        TypeRef::Named(n) => n.clone(),
        _ => "void".to_string(),
    }
}

/// FFI 边界类型：与 Rust 端 ffi_ty 严格对应
fn cpp_ffi_ty(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => cpp_prim(p),
        TypeRef::Named(n) => n.clone(),
        TypeRef::BorrowedStr | TypeRef::OwnedString => "XsoVec<uint8_t>".to_string(),
        TypeRef::Vec(t) => format!("XsoVec<{}>", cpp_elem(t)),
        TypeRef::Owned(t) => format!("{}*", cpp_elem(t)),
        TypeRef::Borrowed(t) => format!("const {}*", cpp_elem(t)),
        TypeRef::Option(t) => format!("const {}*", cpp_elem(t)),
        TypeRef::Result(_, _) => "void*".to_string(),
    }
}

fn gen_enum(out: &mut String, e: &EnumDef) {
    let und = cpp_type(&TypeRef::Primitive(e.underlying.clone()));
    writeln!(out, "enum class {} : {} {{", e.name, und).unwrap();
    for v in &e.variants {
        writeln!(out, "    {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out, "static_assert(sizeof({}) == XSO_LAYOUT_{}_SIZE, \"layout drift\");",
             e.name, e.name).unwrap();
}

fn gen_error(out: &mut String, e: &ErrorDef) {
    let und = cpp_type(&TypeRef::Primitive(e.underlying.clone()));
    writeln!(out, "enum class {} : {} {{", e.name, und).unwrap();
    for v in &e.variants {
        writeln!(out, "    {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out, "static_assert(sizeof({}) == XSO_LAYOUT_{}_SIZE, \"layout drift\");",
             e.name, e.name).unwrap();
}

fn gen_struct(out: &mut String, ir: &BridgeIr, s: &StructDef) {
    writeln!(out, "struct {} {{", s.name).unwrap();
    for f in &s.fields {
        writeln!(out, "    {} {};", cpp_type(&f.ty), f.name).unwrap();
    }
    writeln!(out, "}} __attribute__((packed));").unwrap();

    writeln!(out, "static_assert(sizeof({}) == XSO_LAYOUT_{}_SIZE, \"layout drift\");",
             s.name, s.name).unwrap();
    writeln!(out, "static_assert(alignof({}) == XSO_LAYOUT_{}_ALIGN, \"align drift\");",
             s.name, s.name).unwrap();

    if let Some(fields) = ir.field_offsets(&s.name) {
        for (fname, _, off) in fields {
            writeln!(out, "static_assert(offsetof({}, {}) == {}, \"offset\");",
                     s.name, fname, off).unwrap();
        }
    }
}

fn gen_type_alias(out: &mut String, t: &TypeAliasDef) {
    writeln!(out, "using {} = {};", t.name, cpp_type(&t.target)).unwrap();
}

fn gen_interface(out: &mut String, i: &InterfaceDef) {
    writeln!(out, "class {} {{", i.name).unwrap();
    writeln!(out, "public:").unwrap();
    // VTable：FFI 边界使用稳定 ABI（XsoVec + i32 状态 + out 指针）
    writeln!(out, "    struct VTable {{").unwrap();
    for m in &i.methods {
        let self_ty = match m.self_ownership {
            Some(Ownership::Owned) => "void*",
            Some(Ownership::Borrowed) | Some(Ownership::Value) | None => "const void*",
        };
        let mut params = vec![format!("{} self", self_ty)];
        for p in &m.params {
            params.push(format!("{} {}", cpp_ffi_ty(&p.ty), p.name));
        }
        let (ret_ty, out_param) = match &m.ret {
            TypeRef::Result(ok, _err) => {
                if is_unit(ok) {
                    ("int32_t".to_string(), None)
                } else {
                    ("int32_t".to_string(), Some(format!("{}* out", cpp_ffi_ty(ok))))
                }
            }
            TypeRef::Primitive(p) if p == "unit" => ("void".to_string(), None),
            other => (cpp_ffi_ty(other), None),
        };
        if let Some(op) = out_param {
            params.push(op);
        }
        writeln!(out, "        {} (*{})({});", ret_ty, m.name, params.join(", ")).unwrap();
    }
    writeln!(out, "    }};").unwrap();
    writeln!(out).unwrap();

    // 公共包装方法：保持 xso::Vector / xso::string_view / xso::Result 的易用签名，
    // 内部负责在 FFI 边界类型之间做转换。
    for m in &i.methods {
        // 公共签名（不含 self），使用原始 IDL 类型
        let mut pub_params: Vec<String> = Vec::new();
        for p in &m.params {
            pub_params.push(format!("{} {}", cpp_type(&p.ty), p.name));
        }
        let ret_cpp = cpp_type(&m.ret);
        writeln!(out, "    {} {}({}) {{",
                 ret_cpp, m.name, pub_params.join(", ")).unwrap();

        // 构造 FFI 实参
        let mut call_args: Vec<String> = vec!["self_".to_string()];
        for p in &m.params {
            match &p.ty {
                TypeRef::Vec(inner) => {
                    let vname = format!("{}_v", p.name);
                    let elem = cpp_elem(inner);
                    writeln!(out, "        XsoVec<{}> {} = {{ {}.data(), {}.size() }};",
                             elem, vname, p.name, p.name).unwrap();
                    call_args.push(vname);
                }
                TypeRef::BorrowedStr | TypeRef::OwnedString => {
                    let vname = format!("{}_v", p.name);
                    writeln!(out, "        XsoVec<uint8_t> {} = {{ {}.data(), {}.size() }};",
                             vname, p.name, p.name).unwrap();
                    call_args.push(vname);
                }
                _ => { call_args.push(p.name.clone()); }
            }
        }

        match &m.ret {
            TypeRef::Result(ok, err) => {
                let err_ty = cpp_type(err);
                if is_unit(ok) {
                    writeln!(out, "        int32_t e = vt_->{}({});",
                             m.name, call_args.join(", ")).unwrap();
                    writeln!(out, "        return e == 0 ? xso::Result<void, {}>::ok() : xso::Result<void, {}>::err(static_cast<{}>(e));",
                             err_ty, err_ty, err_ty).unwrap();
                } else {
                    let out_ty = cpp_ffi_ty(ok);
                    writeln!(out, "        {} out{{}};", out_ty).unwrap();
                    call_args.push("&out".to_string());
                    writeln!(out, "        int32_t e = vt_->{}({});",
                             m.name, call_args.join(", ")).unwrap();
                    writeln!(out, "        return e == 0 ? xso::Result<{}, {}>::ok(out) : xso::Result<{}, {}>::err(static_cast<{}>(e));",
                             out_ty, err_ty, out_ty, err_ty, err_ty).unwrap();
                }
            }
            _ => {
                writeln!(out, "        return vt_->{}({});",
                         m.name, call_args.join(", ")).unwrap();
            }
        }
        writeln!(out, "    }}").unwrap();
    }

    writeln!(out).unwrap();
    writeln!(out, "    void* self_ = nullptr;").unwrap();
    writeln!(out, "    VTable* vt_ = nullptr;").unwrap();
    writeln!(out, "}};").unwrap();
}