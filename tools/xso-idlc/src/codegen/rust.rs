//! Rust 后端：全部通过 `Emitter` 的语义方法产出源码，
//! 本文件不出现任何写死的源码字符串（关键字/标点/模板一律来自 `syntax`）。

use crate::ast::*;
use crate::bridge_ir::BridgeIr;
use crate::codegen::emitter::Emitter;
use crate::codegen::naming;
use crate::codegen::syntax;

pub fn generate(ir: &BridgeIr) -> String {
    let module = &ir.module;
    let mut em = Emitter::new();

    // ===== 文件头 =====
    em.rs_comment("AUTO-GENERATED by xso-idlc. DO NOT EDIT.");
    em.rs_comment(&format!("Module: {} v{}", module.name, module.version));
    em.rs_allow(&["non_camel_case_types", "dead_code", "non_upper_case_globals"]);
    em.rs_extern_crate(syntax::rs::ALLOC);
    em.rs_use("alloc::vec::Vec");
    em.rs_use("alloc::boxed::Box");
    let uses_owned_string = module.items.iter().any(|it| match it {
        Item::Struct(s) =>
            s.fields.iter().any(|f| matches!(f.ty, TypeRef::OwnedString)),
        Item::Interface(i) => i.methods.iter().any(|m|
            m.params.iter().any(|p| matches!(p.ty, TypeRef::OwnedString))
            || matches!(&m.ret, TypeRef::Result(ok, _) if matches!(ok.as_ref(), TypeRef::OwnedString))),
        _ => false,
    });
    if uses_owned_string {
        em.rs_use("alloc::string::String");
    }
    em.rs_use("core::ffi::c_void");
    em.blank();

    // ===== 模块 =====
    em.rs_mod_open(&naming::rust_module(&module.name));
    em.rs_use("super::*");
    em.rs_type_alias("string_view<'a>", "&'a str");
    em.rs_type_alias("Result<T, E>", "core::result::Result<T, E>");
    em.blank();

    // ===== 锚点常量（与 anchor / C++ 同源）=====
    for (name, layout) in &ir.type_layouts {
        em.rs_const(false, &naming::rust_layout_const(name, "SIZE"), "usize",
                    &layout.size.to_string());
        em.rs_const(false, &naming::rust_layout_const(name, "ALIGN"), "usize",
                    &layout.align.to_string());
    }
    for (name, layout) in &ir.enum_sizes {
        em.rs_const(false, &naming::rust_layout_const(name, "SIZE"), "usize",
                    &layout.size.to_string());
        em.rs_const(false, &naming::rust_layout_const(name, "ALIGN"), "usize",
                    &layout.align.to_string());
    }
    em.blank();

    // ===== ABI 指纹 =====
    let module_up = module.name.to_uppercase();
    em.rs_doc("ABI 指纹：布局描述符的 FNV-1a 校验和（应与 anchor 头一致）");
    em.rs_const(true, &naming::checksum_const(&module_up), "u32",
                &format!("0x{:08x}", ir.fingerprint()));
    em.rs_const(true, naming::ALGO_VERSION, "u32",
                &crate::bridge_ir::FINGERPRINT_ALGO_VERSION.to_string());
    em.rs_const(true, naming::IR_VERSION, "u32", &ir.ir_version.to_string());
    em.blank();

    // ===== 中间布局：规范桥接载体 =====
    if needs_xso_vec(module) || needs_xso_pair(module) {
        em.rs_comment("===== 中间布局：规范桥接载体（两端逐字节一致） =====");
        if needs_xso_pair(module) {
            em.rs_repr_c();
            em.rs_struct_open(&format!("{}<K, V>", naming::PAIR));
            em.rs_field("key", "K");
            em.rs_field("val", "V");
            em.rs_struct_close();
            em.blank();
        }
        if needs_xso_vec(module) {
            // 参照 cxx：借用视图必须平凡可拷贝、无 Drop，才能按寄存器传参
            em.rs_comment("序列/切片/字符串/集合/关联容器的统一载体：(ptr, len)");
            em.rs_comment("它是**借用视图**（不拥有缓冲），因此无 Drop、恒可平凡拷贝。");
            em.rs_repr_c();
            em.rs_struct_open(&format!("{}<T>", naming::VEC));
            em.rs_field("ptr", "*const T");
            em.rs_field("len", "usize");
            em.rs_struct_close();
            let carrier = format!("{}<u8>", naming::VEC);
            let size_expr = em.rs_size_of(&carrier);
            let align_expr = em.rs_align_of(&carrier);
            em.rs_assert_eq(&size_expr, &naming::CARRIER_SIZE.to_string());
            em.rs_assert_eq(&align_expr, &naming::CARRIER_ALIGN.to_string());

            let impl_ty = format!("{}<T>", naming::VEC);
            em.rs_impl_open(&impl_ty);
            em.rs_fn_one_line(true, "const", "len", "&self", "usize", "self.len");
            em.rs_fn_one_line(true, "const", "is_empty", "&self", "bool", "self.len == 0");
            em.rs_fn_one_line(true, "const", "as_ptr", "&self", "*const T", "self.ptr");
            em.rs_doc("借用视图：调用期间由调用方保证缓冲存活，被调方不得释放该指针。");
            em.rs_doc("");
            em.rs_doc("# Safety");
            em.rs_doc("ptr 必须指向至少 len 个连续元素，且在返回前保持有效。");
            em.rs_fn_open(true, "unsafe", "as_slice<'a>", "&self", "&'a [T]");
            em.stmt("core::slice::from_raw_parts(self.ptr, self.len)");
            em.rs_fn_close();
            em.rs_impl_close();

            // 手工实现：避免 derive 引入多余的 `T: Copy` 约束
            em.rs_impl_open(&format!("Clone for {}", impl_ty));
            em.rs_fn_one_line(false, "", "clone", "&self", "Self", "*self");
            em.rs_impl_close();
            em.rs_impl_open(&format!("Copy for {}", impl_ty));
            em.rs_impl_close();
            em.blank();
        }
    }

    // ===== 条目 =====
    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut em, e),
            Item::Error(e) => gen_error(&mut em, e),
            Item::Struct(s) if !s.opaque => gen_struct(&mut em, ir, s),
            Item::Struct(s) => gen_opaque_struct(&mut em, s),
            Item::Interface(i) => gen_interface(&mut em, ir, i),
            Item::TypeAlias(t) => gen_type_alias(&mut em, t),
        }
        em.blank();
    }

    em.rs_mod_close();
    em.finish()
}

// ===================== 类型映射 =====================

/// 易用侧（trait 内）使用的 Rust 类型
fn rust_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => match p.as_str() {
            "unit" => "()".into(),
            other => other.into(),
        },
        TypeRef::BorrowedStr => "&str".into(),
        TypeRef::OwnedString => "String".into(),
        TypeRef::Named(n) => n.clone(),
        TypeRef::App { name, args } =>
            rust_type(&TypeRef::Named(crate::semantic::mono::mangle(name, args))),
        TypeRef::Vec(t) => format!("Vec<{}>", rust_type(t)),
        TypeRef::Set(t) => format!("Vec<{}>", rust_type(t)),
        TypeRef::Map(k, v) => format!("Vec<({}, {})>", rust_type(k), rust_type(v)),
        TypeRef::Option(t) => format!("Option<{}>", rust_type(t)),
        TypeRef::Owned(t) => format!("Box<{}>", rust_type(t)),
        TypeRef::Borrowed(t) => format!("&{}", rust_type(t)),
        TypeRef::Result(ok, err) =>
            format!("Result<{}, {}>", rust_type(ok), rust_type(err)),
    }
}

fn is_unit(ty: &TypeRef) -> bool {
    matches!(ty, TypeRef::Primitive(p) if p == "unit")
}

/// FFI 边界类型：统一降级为「中间布局」规范载体
fn ffi_ty(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(_) | TypeRef::Named(_) => rust_type(ty),
        TypeRef::App { name, args } =>
            ffi_ty(&TypeRef::Named(crate::semantic::mono::mangle(name, args))),
        TypeRef::BorrowedStr | TypeRef::OwnedString => naming::carrier(naming::VEC, "u8"),
        TypeRef::Vec(t) => naming::carrier(naming::VEC, &ffi_ty(t)),
        TypeRef::Set(t) => naming::carrier(naming::VEC, &ffi_ty(t)),
        TypeRef::Map(k, v) => naming::carrier(naming::VEC,
            &naming::carrier(naming::PAIR, &format!("{}, {}", ffi_ty(k), ffi_ty(v)))),
        TypeRef::Owned(t) => format!("*mut {}", rust_type(t)),
        TypeRef::Borrowed(t) => format!("*const {}", rust_type(t)),
        TypeRef::Option(t) => format!("*const {}", rust_type(t)),
        TypeRef::Result(_, _) => "*const c_void".to_string(),
    }
}

fn needs_xso_vec(module: &Module) -> bool {
    module.items.iter().any(|it| match it {
        Item::Struct(s) => s.fields.iter().any(|f| uses_bridge_vec(&f.ty)),
        Item::Interface(i) => i.methods.iter().any(|m| {
            m.params.iter().any(|p| uses_bridge_vec(&p.ty))
            || matches!(&m.ret, TypeRef::Result(ok, _) if !is_unit(ok) && uses_bridge_vec(ok))
        }),
        _ => false,
    })
}

fn needs_xso_pair(module: &Module) -> bool {
    module.items.iter().any(|it| match it {
        Item::Struct(s) => s.fields.iter().any(|f| matches!(f.ty, TypeRef::Map(_, _))),
        Item::Interface(i) => i.methods.iter().any(|m| {
            m.params.iter().any(|p| matches!(p.ty, TypeRef::Map(_, _)))
            || matches!(&m.ret, TypeRef::Result(ok, _) if matches!(ok.as_ref(), TypeRef::Map(_, _)))
        }),
        _ => false,
    })
}

fn uses_bridge_vec(ty: &TypeRef) -> bool {
    matches!(ty,
        TypeRef::Vec(_) | TypeRef::Set(_) | TypeRef::Map(_, _)
        | TypeRef::BorrowedStr | TypeRef::OwnedString)
}

// ===================== 条目生成 =====================

/// 判别式安全转换：`from_code` / `code`
fn gen_codec(em: &mut Emitter, name: &str, variants: &[Variant]) {
    em.rs_impl_open(name);
    em.rs_doc("由边界错误码安全转换；None = 非法判别式（须 fail-closed）");
    em.rs_fn_open(true, "", "from_code", "code: i32", "Option<Self>");
    em.rs_match_open("code");
    for v in variants {
        em.rs_match_arm(&(v.value as i32).to_string(), &syntax::rs::some_ctor(&v.name));
    }
    em.rs_match_wildcard(&syntax::rs::none());
    em.rs_match_close();
    em.rs_fn_close();
    em.rs_doc("枚举 -> 边界错误码");
    em.rs_fn_one_line(true, "", "code", "self", "i32", "self as i32");
    em.rs_impl_close();
}

fn gen_enum(em: &mut Emitter, e: &EnumDef) {
    let repr = match e.underlying.as_str() {
        "u8" | "u16" | "u32" | "u64" | "i8" | "i16" | "i32" | "i64" => &e.underlying,
        _ => "u32",
    };
    em.rs_repr(repr);
    em.rs_derive(&syntax::rs::DERIVE_POD);
    em.rs_enum_open(&e.name);
    for v in &e.variants { em.rs_variant(&v.name, v.value); }
    em.rs_enum_close();
    let size_expr = em.rs_size_of(&e.name);
    em.rs_assert_eq(&size_expr, &naming::rust_layout_const(&e.name, "SIZE"));
    gen_codec(em, &e.name, &e.variants);
}

fn gen_error(em: &mut Emitter, e: &ErrorDef) {
    let repr = match e.underlying.as_str() {
        "u8" | "u16" | "u32" | "u64" | "i8" | "i16" | "i32" | "i64" => &e.underlying,
        _ => "i32",
    };
    em.rs_repr(repr);
    em.rs_derive(&syntax::rs::DERIVE_POD);
    em.rs_enum_open(&e.name);
    for v in &e.variants { em.rs_variant(&v.name, v.value); }
    em.rs_enum_close();
    let size_expr = em.rs_size_of(&e.name);
    em.rs_assert_eq(&size_expr, &naming::rust_layout_const(&e.name, "SIZE"));
    gen_codec(em, &e.name, &e.variants);
}

fn gen_struct(em: &mut Emitter, ir: &BridgeIr, s: &StructDef) {
    let trivial = s.fields.iter()
        .all(|f| matches!(f.ty, TypeRef::Primitive(_) | TypeRef::Named(_)));
    let derives: Vec<&str> = if trivial { vec!["Clone", "Copy"] } else { vec!["Clone"] };
    em.rs_repr_c();
    em.rs_derive(&derives);
    em.rs_struct_open(&s.name);
    for f in &s.fields { em.rs_field(&f.name, &ffi_ty(&f.ty)); }
    em.rs_struct_close();

    let size_expr = em.rs_size_of(&s.name);
    let align_expr = em.rs_align_of(&s.name);
    em.rs_assert_eq(&size_expr, &naming::rust_layout_const(&s.name, "SIZE"));
    em.rs_assert_eq(&align_expr, &naming::rust_layout_const(&s.name, "ALIGN"));

    if let Some(fields) = ir.field_offsets(&s.name) {
        for (fname, _, off) in fields {
            let off_expr = em.rs_offset_of(&s.name, fname);
            em.rs_assert_eq(&off_expr, &off.to_string());
        }
    }
}

fn gen_opaque_struct(em: &mut Emitter, s: &StructDef) {
    em.rs_comment("不透明：字段隐藏，仅允许指针传递");
    em.rs_repr_c();
    em.rs_struct_open(&s.name);
    em.rs_field("_private", "[u8; 0]");
    em.rs_struct_close();
}

fn gen_type_alias(em: &mut Emitter, t: &TypeAliasDef) {
    em.rs_type_alias(&t.name, &rust_type(&t.target));
}

fn gen_interface(em: &mut Emitter, _ir: &BridgeIr, i: &InterfaceDef) {
    // 业务实现侧：安全 trait
    em.rs_comment("trait：业务实现侧（安全、易用）");
    em.rs_trait_open(&i.name);
    for m in &i.methods {
        let mut params = Vec::new();
        match m.self_ownership {
            Some(Ownership::Owned) => params.push("self: Box<Self>".to_string()),
            Some(Ownership::Borrowed) | Some(Ownership::Value) | None =>
                params.push("&self".to_string()),
        }
        for p in &m.params {
            params.push(format!("{}: {}", p.name, rust_type(&p.ty)));
        }
        em.rs_trait_fn(&m.name, &params.join(", "), &rust_type(&m.ret));
    }
    em.rs_trait_close();
    em.blank();

    // VTable：FFI 边界，稳定 ABI
    em.rs_comment("vtable（类型擦除，供 C++ 调用）：FFI 边界使用稳定 ABI");
    em.rs_comment("  - 切片/字符串/集合/关联容器 -> XsoVec 规范载体（指针+长度）");
    em.rs_comment("  - Result<T,E> -> i32 状态码 + 可选的 *mut T 输出指针（0 表示成功）");
    em.rs_repr_c();
    em.rs_struct_open(&format!("{}VTable", i.name));
    for m in &i.methods {
        let self_ty = match m.self_ownership {
            Some(Ownership::Owned) => "*mut c_void",
            Some(Ownership::Borrowed) | Some(Ownership::Value) | None => "*const c_void",
        };
        let mut params = vec![format!("self_: {}", self_ty)];
        for p in &m.params {
            params.push(format!("{}: {}", p.name, ffi_ty(&p.ty)));
        }

        let (ret_ty, out_param) = match &m.ret {
            TypeRef::Result(ok, _err) => {
                if is_unit(ok) {
                    ("i32".to_string(), None)
                } else {
                    ("i32".to_string(), Some(format!("out: *mut {}", ffi_ty(ok))))
                }
            }
            TypeRef::Primitive(p) if p == "unit" => ("()".to_string(), None),
            other => (ffi_ty(other), None),
        };
        if let Some(op) = out_param { params.push(op); }

        em.rs_fn_ptr(&m.name, &params.join(", "), &ret_ty);
    }
    em.rs_struct_close();
}
