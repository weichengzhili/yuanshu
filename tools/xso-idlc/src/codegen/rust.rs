use crate::ast::*;
use crate::bridge_ir::BridgeIr;
use std::fmt::Write;

pub fn generate(ir: &BridgeIr) -> String {
    let module = &ir.module;
    let mut out = String::new();

    writeln!(out, "// AUTO-GENERATED by xso-idlc 0.1.0. DO NOT EDIT.").unwrap();
    writeln!(out, "// Module: {} v{}", module.name, module.version).unwrap();
    writeln!(out, "#![allow(non_camel_case_types, dead_code, non_upper_case_globals)]").unwrap();
    writeln!(out, "extern crate alloc;").unwrap();
    writeln!(out, "use alloc::vec::Vec;").unwrap();
    writeln!(out, "use alloc::boxed::Box;").unwrap();
    let uses_owned_string = module.items.iter().any(|it| match it {
        Item::Struct(s) =>
            s.fields.iter().any(|f| matches!(f.ty, TypeRef::OwnedString)),
        Item::Interface(i) => i.methods.iter().any(|m|
            m.params.iter().any(|p| matches!(p.ty, TypeRef::OwnedString))
            || matches!(&m.ret, TypeRef::Result(ok, _) if matches!(ok.as_ref(), TypeRef::OwnedString))),
        _ => false,
    });
    if uses_owned_string {
        writeln!(out, "use alloc::string::String;").unwrap();
    }
    writeln!(out, "use core::ffi::c_void;").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "pub mod {}_bridge {{", module.name).unwrap();
    writeln!(out, "    use super::*;").unwrap();
    // 类型别名（指向内核提供的 string_view / Result）
    writeln!(out, "    pub type string_view<'a> = &'a str;").unwrap();
    writeln!(out, "    pub type Result<T, E> = core::result::Result<T, E>;").unwrap();
    writeln!(out).unwrap();

    // 锚点常量（从 anchor 同步）
    for (name, layout) in &ir.type_layouts {
        writeln!(out, "    const LAYOUT_{}_SIZE:  usize = {};", name, layout.size).unwrap();
        writeln!(out, "    const LAYOUT_{}_ALIGN: usize = {};", name, layout.align).unwrap();
    }
    for (name, layout) in &ir.enum_sizes {
        writeln!(out, "    const LAYOUT_{}_SIZE:  usize = {};", name, layout.size).unwrap();
        writeln!(out, "    const LAYOUT_{}_ALIGN: usize = {};", name, layout.align).unwrap();
    }
    writeln!(out).unwrap();

    // FFI 边界的切片/字符串载体：(ptr, len)，POD，C++ 端有完全一致的模板
    if needs_xso_vec(module) {
        writeln!(out, "    // FFI 边界载体：切片/字符串以 (指针, 长度) 传递，布局稳定").unwrap();
        writeln!(out, "    #[repr(C)]").unwrap();
        writeln!(out, "    pub struct XsoVec<T> {{").unwrap();
        writeln!(out, "        pub ptr: *const T,").unwrap();
        writeln!(out, "        pub len: usize,").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();
    }

    for item in &module.items {
        match item {
            Item::Enum(e) => gen_enum(&mut out, e),
            Item::Error(e) => gen_error(&mut out, e),
            Item::Struct(s) if !s.opaque => gen_struct(&mut out, ir, s),
            Item::Struct(s) => gen_opaque_struct(&mut out, s),
            Item::Interface(i) => gen_interface(&mut out, ir, i),
            Item::TypeAlias(t) => gen_type_alias(&mut out, t),
        }
        writeln!(out).unwrap();
    }

    writeln!(out, "}}").unwrap();
    out
}

fn rust_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Primitive(p) => match p.as_str() {
            "unit" => "()".into(),
            other => other.into(),
        },
        TypeRef::BorrowedStr => "&str".into(),
        TypeRef::OwnedString => "String".into(),
        TypeRef::Named(n) => n.clone(),
        TypeRef::Vec(t) => format!("Vec<{}>", rust_type(t)),
        TypeRef::Option(t) => format!("Option<{}>", rust_type(t)),
        TypeRef::Owned(t) => format!("Box<{}>", rust_type(t)),
        TypeRef::Borrowed(t) => format!("&{}", rust_type(t)),
        TypeRef::Result(ok, err) =>
            format!("Result<{}, {}>", rust_type(ok), rust_type(err)),
    }
}

fn is_unit(ty: &TypeRef) -> bool {
    matches!(ty, TypeRef::Primitive(p) if p == "unit")
}

/// FFI 边界类型：把一切在 C ABI 下布局不稳的类型（Vec / 字符串 / Box / 引用）
/// 统一降级为稳定的表示，保证与 C++ 端逐字节一致。
fn ffi_ty(ty: &TypeRef) -> String {
    match ty {
        // 标量 / 具名类型按值传递（它们本身已是 #[repr(C)] / 基础类型）
        TypeRef::Primitive(_) | TypeRef::Named(_) => rust_type(ty),
        // 切片 / 字符串：降级为 (ptr, len) 的 XsoVec
        TypeRef::BorrowedStr | TypeRef::OwnedString => "XsoVec<u8>".to_string(),
        TypeRef::Vec(t) => format!("XsoVec<{}>", rust_type(t)),
        // 所有权指针：直接传裸指针
        TypeRef::Owned(t) => format!("*mut {}", rust_type(t)),
        TypeRef::Borrowed(t) => format!("*const {}", rust_type(t)),
        TypeRef::Option(t) => format!("*const {}", rust_type(t)),
        // Result 不会作为普通参数出现
        TypeRef::Result(_, _) => "*const c_void".to_string(),
    }
}

/// 是否为 ABI 边界上需要 XsoVec 的情况（切片/字符串参数或返回）
fn needs_xso_vec(module: &Module) -> bool {
    module.items.iter().any(|it| match it {
        Item::Interface(i) => i.methods.iter().any(|m| {
            m.params.iter().any(|p|
                matches!(p.ty, TypeRef::Vec(_) | TypeRef::BorrowedStr | TypeRef::OwnedString))
            || matches!(&m.ret,
                TypeRef::Result(ok, _) if !is_unit(ok)
                    && matches!(ok.as_ref(), TypeRef::Vec(_) | TypeRef::BorrowedStr | TypeRef::OwnedString))
        }),
        _ => false,
    })
}

fn gen_enum(out: &mut String, e: &EnumDef) {
    let repr = match e.underlying.as_str() {
        "u8" | "u16" | "u32" | "u64" | "i8" | "i16" | "i32" | "i64" => &e.underlying,
        _ => "u32",
    };
    writeln!(out, "    #[repr({})]", repr).unwrap();
    writeln!(out, "    #[derive(Clone, Copy, PartialEq, Eq, Debug)]").unwrap();
    writeln!(out, "    pub enum {} {{", e.name).unwrap();
    for v in &e.variants {
        writeln!(out, "        {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    const _: () = assert!(core::mem::size_of::<{}>() == LAYOUT_{}_SIZE);",
             e.name, e.name).unwrap();
}

fn gen_error(out: &mut String, e: &ErrorDef) {
    let repr = match e.underlying.as_str() {
        "u8" | "u16" | "u32" | "u64" | "i8" | "i16" | "i32" | "i64" => &e.underlying,
        _ => "i32",
    };
    writeln!(out, "    #[repr({})]", repr).unwrap();
    writeln!(out, "    #[derive(Clone, Copy, PartialEq, Eq, Debug)]").unwrap();
    writeln!(out, "    pub enum {} {{", e.name).unwrap();
    for v in &e.variants {
        writeln!(out, "        {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    const _: () = assert!(core::mem::size_of::<{}>() == LAYOUT_{}_SIZE);",
             e.name, e.name).unwrap();
}

fn gen_struct(out: &mut String, ir: &BridgeIr, s: &StructDef) {
    writeln!(out, "    #[repr(C, packed)]").unwrap();
    writeln!(out, "    #[derive(Clone, Copy)]").unwrap();
    writeln!(out, "    pub struct {} {{", s.name).unwrap();
    for f in &s.fields {
        writeln!(out, "        pub {}: {},", f.name, rust_type(&f.ty)).unwrap();
    }
    writeln!(out, "    }}").unwrap();

    writeln!(out, "    const _: () = assert!(core::mem::size_of::<{}>() == LAYOUT_{}_SIZE);",
             s.name, s.name).unwrap();
    writeln!(out, "    const _: () = assert!(core::mem::align_of::<{}>() == LAYOUT_{}_ALIGN);",
             s.name, s.name).unwrap();

    if let Some(fields) = ir.field_offsets(&s.name) {
        for (fname, _, off) in fields {
            writeln!(out, "    const _: () = assert!(core::mem::offset_of!({}, {}) == {});",
                     s.name, fname, off).unwrap();
        }
    }
}

fn gen_opaque_struct(out: &mut String, s: &StructDef) {
    // 不透明：字段隐藏，仅允许指针传递
    writeln!(out, "    #[repr(C)]").unwrap();
    writeln!(out, "    pub struct {} {{ _private: [u8; 0] }}", s.name).unwrap();
    writeln!(out, "    // opaque type: fields hidden by design").unwrap();
}

fn gen_type_alias(out: &mut String, t: &TypeAliasDef) {
    writeln!(out, "    pub type {} = {};", t.name, rust_type(&t.target)).unwrap();
}

fn gen_interface(out: &mut String, _ir: &BridgeIr, i: &InterfaceDef) {
    // trait
    writeln!(out, "    pub trait {} {{", i.name).unwrap();
    for m in &i.methods {
        let mut params = Vec::new();
        match m.self_ownership {
            Some(Ownership::Owned) => params.push("self: Box<Self>".to_string()),
            Some(Ownership::Borrowed) | Some(Ownership::Value) | None =>
                params.push("&self".to_string()),
        }
        for p in &m.params {
            params.push(format!("{}: {}", p.name, rust_type(&p.ty)));
        }
        writeln!(out, "        fn {}({}) -> {};",
                 m.name, params.join(", "), rust_type(&m.ret)).unwrap();
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    // vtable（类型擦除，供 C++ 调用）：FFI 边界使用稳定 ABI
    //   - 切片/字符串 -> XsoVec<T>（指针+长度）
    //   - Result<T,E> -> i32 状态码 + 可选的 *mut T 输出指针（0 表示成功）
    writeln!(out, "    #[repr(C)]").unwrap();
    writeln!(out, "    pub struct {}VTable {{", i.name).unwrap();
    for m in &i.methods {
        let self_ty = match m.self_ownership {
            Some(Ownership::Owned) => "*mut c_void",
            Some(Ownership::Borrowed) | Some(Ownership::Value) | None => "*const c_void",
        };
        let mut params = vec![format!("self_: {}", self_ty)];
        for p in &m.params {
            params.push(format!("{}: {}", p.name, ffi_ty(&p.ty)));
        }

        // 返回约定
        let (ret_ty, out_param) = match &m.ret {
            TypeRef::Result(ok, _err) => {
                if is_unit(ok) {
                    ("i32".to_string(), None)
                } else {
                    ("i32".to_string(), Some(format!("out: *mut {}", ffi_ty(ok))))
                }
            }
            TypeRef::Primitive(p) if p == "unit" => ("()".to_string(), None),
            other => (ffi_ty(other), None),
        };
        if let Some(op) = out_param {
            params.push(op);
        }

        writeln!(out, "        pub {}: unsafe extern \"C\" fn({}) -> {},",
                 m.name, params.join(", "), ret_ty).unwrap();
    }
    writeln!(out, "    }}").unwrap();
}